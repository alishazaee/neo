CREATE TABLE regional_travel_results (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    job_id bigint NOT NULL,
    username varchar(255) NOT NULL,
    source_region_geohash varchar(12) NOT NULL,
    destination_region_geohash varchar(12) NOT NULL,
    departure_time timestamp NOT NULL,
    arrival_time timestamp NOT NULL,
    CONSTRAINT pk_regional_travel_results PRIMARY KEY (job_id, id),
    CONSTRAINT fk_regional_travel_results_job
        FOREIGN KEY (job_id) REFERENCES async_jobs (id) ON DELETE CASCADE,
    CONSTRAINT ck_regional_travel_results_time_order
        CHECK (arrival_time >= departure_time)
) PARTITION BY HASH (job_id);

DO $$
BEGIN
    FOR partition_number IN 0..15 LOOP
        EXECUTE format(
            'CREATE TABLE regional_travel_results_p%s PARTITION OF regional_travel_results '
                || 'FOR VALUES WITH (MODULUS 16, REMAINDER %s)',
            partition_number,
            partition_number
        );
    END LOOP;
END
$$;
